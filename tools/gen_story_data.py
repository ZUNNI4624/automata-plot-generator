def w(exp, weight=1):
    return {"expansion": exp if isinstance(exp, list) else [exp], "weight": weight}


def write_json(name, obj):
    path = os.path.join(ROOT, name)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(obj, f, indent=2, ensure_ascii=False)
    print("wrote", path)


