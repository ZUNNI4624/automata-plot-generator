def gen_lines(prefix_style, n, base_phrases, more=None):
    lines = list(base_phrases)
    if more:
        lines.extend(more)
    while len(lines) < n:
        lines.append(lines[len(lines) % len(base_phrases)] + f" ({len(lines)})")
    return [w(x) for x in lines[:n]]


